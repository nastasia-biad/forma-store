/** Old journal URLs. Each one opens the note that continues the same subject. */
export const legacyArticleRedirects: Readonly<Record<string, string>> = {
  'dub-v-odnoy-komnate': 'proporcii-vazhnee-dekora',
  'latun-len-i-pesok': 'derevo-metall-tekstil',
  'olivkovyy-tekstil': 'spokojnyj-interer',
}

export function findArticle(slug: string): JournalArticle | undefined {
  const canonical = legacyArticleRedirects[slug] ?? slug
  return journalArticles.find((article) => article.slug === canonical)
}
