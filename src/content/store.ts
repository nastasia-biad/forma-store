export function categoryCount(products: readonly Product[], category: ShopCategory): number {
  return products.filter((product) => {
    if (category.category && product.category !== category.category) {
      return false
    }

    if (category.subcategory && product.subcategory !== category.subcategory) {
      return false
    }

    return true
  }).length
}

