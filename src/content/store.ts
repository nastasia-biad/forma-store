export function publishedContacts(): StoreContact[] {
  return (Object.keys(contactLabels) as StoreContactId[])
    .map((id) => ({
      id,
      label: contactLabels[id],
      value: storeContacts[id].trim(),
    }))
    .filter((contact) => contact.value !== '')
}

